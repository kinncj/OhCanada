import { chromium } from '@playwright/test';
import { spawn } from 'node:child_process';
import { writeFileSync } from 'node:fs';
const server = spawn('npx', ['vite', 'preview', '--port', '4173', '--strictPort'], { stdio: 'ignore' });
await new Promise((r) => setTimeout(r, 2500));
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 960, height: 540 } });
const errs = [];
page.on('console', (m) => { if (m.text().includes('Shader Error') || m.text().includes('ERROR: 0:')) errs.push(m.text()); });
await page.goto(`http://localhost:4173/OhCanada/?e2e=1&preset=${process.argv[2] ?? 'low'}`, { waitUntil: 'load' });
await page.getByTestId('menu-new').waitFor({ timeout: 60000 });
await page.getByTestId('menu-new').click();
await page.waitForTimeout(8000);
writeFileSync(process.argv[3] ?? 'shader-errors.txt', errs.join('\n\n=====\n\n'));
console.log('errors:', errs.length);
await browser.close(); server.kill(); process.exit(0);
